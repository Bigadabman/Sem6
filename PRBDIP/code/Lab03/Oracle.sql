CREATE OR REPLACE PROCEDURE changeParent(
    p_OldParentName VARCHAR2,
    p_NewParentName VARCHAR2
)
IS
    v_oldParent NUMBER;
    v_newParent NUMBER;
BEGIN

    SELECT Id INTO v_oldParent
    FROM Skill
    WHERE SkillName = p_OldParentName;

    SELECT Id INTO v_newParent
    FROM Skill
    WHERE SkillName = p_NewParentName;

    UPDATE Skill
    SET ParentId = v_newParent
    WHERE ParentId = v_oldParent;

END;
/


